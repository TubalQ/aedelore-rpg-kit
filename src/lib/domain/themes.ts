// Palettes are runtime-editable data now (the `palettes` system kind), so a
// palette id is any string. THEMES stays as the bundled seed/fallback.
export type ThemeId = string;
export type Palette = { label?: string; description?: string; colors: Record<string, string> };
export const THEME_IDS = Object.keys(THEMES);
export const DEFAULT_THEME = "dark-glass";

// Palettes come from the DB-backed active system (the `palettes` kind, edited in
// /system-admin). These two helpers centralise the "live palettes, else the
// bundled THEMES" fallback + default-id pick that the theme store, settings page
// and the pre-paint <ThemeScript> all need (client and server) - previously
// copy-pasted in three places.

/** The live palettes if present, otherwise the bundled THEMES seed. */
export function resolvePalettes<T>(live: T | undefined | null): T {
  return live && Object.keys(live as object).length > 0
    ? live
    : (THEMES as unknown as T);
}

/** The default palette id: DEFAULT_THEME if available, else the first one. */
export function pickDefaultThemeId(palettes: Record<string, unknown>): string {
  return DEFAULT_THEME in palettes ? DEFAULT_THEME : Object.keys(palettes)[0] ?? DEFAULT_THEME;
}
