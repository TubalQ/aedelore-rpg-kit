// Palettes are runtime-editable data now (the `palettes` system kind), so a
// palette id is any string. THEMES stays as the bundled seed/fallback.
export type ThemeId = string;
export type Palette = { label?: string; description?: string; descriptionSv?: string; colors: Record<string, string> };
export const THEME_IDS = Object.keys(THEMES);
export const DEFAULT_THEME = "dark-glass";

// Palettes come from the DB-backed active system (the `palettes` kind, edited in
// /system-admin). These two helpers centralise the "live palettes, else the
// bundled THEMES" fallback + default-id pick that the theme store, settings page
// and the pre-paint <ThemeScript> all need (client and server) - previously
// copy-pasted in three places.

/** The live palettes if present, otherwise the bundled THEMES seed. */
export function resolvePalettes<T>(live: T | undefined | null): T {
  return live && Object.keys(live as object).length > 0
    ? live
    : (THEMES as unknown as T);
}

/**
 * The theme's accent colour on the default palette (Y9). Every palette carries
 * its own accent-gold, so the theme editor's "Accent colour" was always
 * overwritten and had no effect. It now colours the default palette; the other
 * palettes keep their own accent, which is part of their look.
 */
export function withThemeAccent<T extends Record<string, { colors: Record<string, string> }>>(
  palettes: T,
  theme: { accentColor?: string; accentColorDim?: string } | undefined,
): T {
  const id = pickDefaultThemeId(palettes);
  const base = palettes[id];
  if (!base || !theme?.accentColor) return palettes;
  const colors = { ...base.colors, "accent-gold": theme.accentColor, ...(theme.accentColorDim ? { "accent-gold-dim": theme.accentColorDim } : {}) };
  return { ...palettes, [id]: { ...base, colors } };
}

/** The default palette id: DEFAULT_THEME if available, else the first one. */
export function pickDefaultThemeId(palettes: Record<string, unknown>): string {
  return DEFAULT_THEME in palettes ? DEFAULT_THEME : Object.keys(palettes)[0] ?? DEFAULT_THEME;
}

/** Relative luminance (0..1) of a #rgb / #rrggbb colour, sRGB-weighted. */
export function colorLuminance(hex: string): number {
  const h = hex.replace("#", "");
  const full = h.length === 3 ? h.split("").map((c) => c + c).join("") : h;
  if (full.length !== 6) return 0;
  const r = parseInt(full.slice(0, 2), 16);
  const g = parseInt(full.slice(2, 4), 16);
  const b = parseInt(full.slice(4, 6), 16);
  return (0.2126 * r + 0.7152 * g + 0.0722 * b) / 255;
}

/** A palette reads as "light" when its page background (bg-base) is bright.
    Lets a light/dark toggle classify any palette without a stored flag. */
export function paletteIsLight(colors: Record<string, string>): boolean {
  const bg = colors["bg-base"];
  return bg ? colorLuminance(bg) > 0.5 : false;
}

/** WCAG contrast ratio (1..21) between two #rgb / #rrggbb colours. */
export function contrastRatio(a: string, b: string): number {
  const lin = (hex: string): number => {
    const h = hex.replace("#", "");
    const full = h.length === 3 ? h.split("").map((c) => c + c).join("") : h;
    if (full.length !== 6) return 0;
    const [r, g, bl] = [0, 2, 4].map((i) => {
      const c = parseInt(full.slice(i, i + 2), 16) / 255;
      return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
    });
    return 0.2126 * r + 0.7152 * g + 0.0722 * bl;
  };
  const [hi, lo] = [lin(a), lin(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
}

const ON_ACCENT_LIGHT = "#ffffff";
const ON_ACCENT_DARK = "#0b0a10";

/**
 * Y17: text on an accent-purple button. White was hardcoded and fell to 3:1
 * on the lighter purples (necro, forest, frost). Each palette gets
 * `on-accent-purple`, white or near-black, whichever reads better on its purple.
 */
export function withOnAccent<T extends Record<string, { colors: Record<string, string> }>>(palettes: T): T {
  const out: Record<string, { colors: Record<string, string> }> = {};
  for (const [id, p] of Object.entries(palettes)) {
    const purple = p.colors["accent-purple"];
    if (!purple || p.colors["on-accent-purple"]) {
      out[id] = p;
      continue;
    }
    const on = contrastRatio(purple, ON_ACCENT_LIGHT) >= contrastRatio(purple, ON_ACCENT_DARK) ? ON_ACCENT_LIGHT : ON_ACCENT_DARK;
    out[id] = { ...p, colors: { ...p.colors, "on-accent-purple": on } };
  }
  return out as T;
}
